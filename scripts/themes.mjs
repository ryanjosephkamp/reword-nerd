// Writes src/styles/palettes.css (and the swatches in src/shared/palettes.ts): every color palette in a dark and a light version, built
// from OKLCH so the palettes share one lightness scale and only their hue changes. It also
// checks each pair the interface relies on against WCAG contrast and stops on a failure.
// Run with: node scripts/themes.mjs
import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");

// Each palette tints the neutrals with one hue and picks an accent for each mode.
// `tint` scales the neutrals' chroma: 1 is the original blue graphite.
export const PALETTES = [
  {
    id: "harbor",
    label: "Harbor",
    hue: 235,
    tint: 1,
    dark: [0.846, 0.068, 223],
    light: [0.483, 0.083, 229],
  },
  {
    id: "moss",
    label: "Moss",
    hue: 155,
    tint: 0.85,
    dark: [0.84, 0.085, 152],
    light: [0.47, 0.085, 152],
  },
  {
    id: "ember",
    label: "Ember",
    hue: 60,
    tint: 0.8,
    dark: [0.84, 0.095, 72],
    light: [0.5, 0.11, 50],
  },
  {
    id: "plum",
    label: "Plum",
    hue: 305,
    tint: 0.9,
    dark: [0.83, 0.075, 312],
    light: [0.48, 0.12, 312],
  },
  {
    id: "graphite",
    label: "Graphite",
    hue: 250,
    tint: 0.12,
    dark: [0.9, 0.006, 250],
    light: [0.32, 0.006, 250],
  },
];

// Lightness and chroma for each neutral role, from the original palette.
const DARK = {
  bg: [0.218, 0.02],
  panel: [0.249, 0.022],
  raised: [0.3, 0.028],
  line: [0.353, 0.03],
  "line-strong": [0.439, 0.038],
  text: [0.951, 0.008],
  muted: [0.769, 0.024],
  faint: [0.675, 0.027],
};
const LIGHT = {
  bg: [0.966, 0.003],
  panel: [1, 0],
  raised: [0.949, 0.007],
  line: [0.896, 0.011],
  "line-strong": [0.821, 0.019],
  text: [0.249, 0.023],
  muted: [0.482, 0.028],
  faint: [0.52, 0.026],
};

function linearToSrgb(channel) {
  const c = Math.min(1, Math.max(0, channel));
  return c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055;
}

function srgbToLinear(channel) {
  const c = channel / 255;
  return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
}

export function oklchToHex([lightness, chroma, hue]) {
  const a = chroma * Math.cos((hue * Math.PI) / 180);
  const b = chroma * Math.sin((hue * Math.PI) / 180);
  const l = (lightness + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (lightness - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (lightness - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const rgb = [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
  return `#${rgb
    .map((channel) =>
      Math.round(linearToSrgb(channel) * 255)
        .toString(16)
        .padStart(2, "0"),
    )
    .join("")}`;
}

function luminance(hex) {
  const [r, g, b] = [1, 3, 5].map((at) => srgbToLinear(parseInt(hex.slice(at, at + 2), 16)));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

export function contrast(first, second) {
  const [high, low] = [luminance(first), luminance(second)].sort((x, y) => y - x);
  return (high + 0.05) / (low + 0.05);
}

function neutrals(scale, palette) {
  return Object.fromEntries(
    Object.entries(scale).map(([role, [lightness, chroma]]) => [
      role,
      oklchToHex([lightness, chroma * palette.tint, palette.hue]),
    ]),
  );
}

function modeColors(palette, mode) {
  const colors = neutrals(mode === "dark" ? DARK : LIGHT, palette);
  const [lightness, chroma, hue] = palette[mode];
  colors.accent = oklchToHex([lightness, chroma, hue]);
  colors["accent-strong"] =
    mode === "dark"
      ? oklchToHex([Math.min(0.94, lightness + 0.06), chroma * 0.65, hue])
      : oklchToHex([lightness - 0.09, chroma * 0.85, hue]);
  colors["accent-ink"] = mode === "dark" ? oklchToHex([0.248, 0.032, hue]) : "#ffffff";
  return colors;
}

const failures = [];
function check(label, first, second, minimum) {
  const ratio = contrast(first, second);
  if (ratio < minimum) failures.push(`${label}: ${ratio.toFixed(2)} (needs ${minimum})`);
}

const swatches = [];
let css = `/* Generated by scripts/themes.mjs; edit the script, not this file.
   Each palette sets dark (--d-*) and light (--l-*) colors; tokens.css picks one set. */\n`;

for (const palette of PALETTES) {
  const selector =
    palette.id === "harbor"
      ? `:root,\n:root[data-palette="harbor"]`
      : `:root[data-palette="${palette.id}"]`;
  const lines = [];
  const swatch = { id: palette.id, label: palette.label };
  for (const mode of ["dark", "light"]) {
    const colors = modeColors(palette, mode);
    swatch[mode] = { bg: colors.bg, accent: colors.accent };
    const prefix = mode === "dark" ? "d" : "l";
    for (const [role, value] of Object.entries(colors))
      lines.push(`  --${prefix}-${role}: ${value};`);
    const name = `${palette.id} ${mode}`;
    for (const surface of ["bg", "panel", "raised"]) {
      check(`${name} text on ${surface}`, colors.text, colors[surface], 7);
      check(`${name} muted on ${surface}`, colors.muted, colors[surface], 4.5);
      check(`${name} faint on ${surface}`, colors.faint, colors[surface], 4.5);
      check(`${name} accent on ${surface}`, colors.accent, colors[surface], 4.5);
    }
    check(`${name} button text`, colors["accent-ink"], colors.accent, 4.5);
    check(`${name} button hover text`, colors["accent-ink"], colors["accent-strong"], 4.5);
    check(
      `${name} control border`,
      colors["line-strong"],
      colors.panel,
      mode === "dark" ? 1.6 : 1.4,
    );
  }
  // Links on light paper use the light accent.
  check(`${palette.id} link on paper`, oklchToHex(palette.light), "#f6f4ec", 4.5);
  css += `\n${selector} {\n${lines.join("\n")}\n}\n`;
  swatches.push(swatch);
}

if (failures.length) {
  console.error(`Contrast failures:\n${failures.join("\n")}`);
  process.exit(1);
}

writeFileSync(join(root, "src/styles/palettes.css"), css);
writeFileSync(
  join(root, "src/shared/palettes.ts"),
  `// Generated by scripts/themes.mjs; edit the script, not this file.\n\nexport const PALETTES = ${JSON.stringify(swatches, null, 2)} as const;\n\nexport type PaletteId = (typeof PALETTES)[number]["id"];\n`,
);
console.log(`Wrote ${PALETTES.length} palettes.`);
