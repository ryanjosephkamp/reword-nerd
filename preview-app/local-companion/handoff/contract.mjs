import { createHash } from "node:crypto";
import { open, realpath, lstat } from "node:fs/promises";
import { constants } from "node:fs";
import { resolve, join } from "node:path";
export const HANDOFF_VERSION = 1;
export const unsafePromptControls = (text) =>
  [...text].some((c) => {
    const n = c.codePointAt(0);
    return (n < 32 && n !== 9 && n !== 10) || n === 127;
  });
export const MAX_PROMPT = 64 * 1024;
export const MAX_HANDOFFS = 16;
export const FILE_LIMITS = Object.freeze({
  "package.zip": 24 * 1024 * 1024,
  "reference.png": 8 * 1024 * 1024,
  "reviewed-source.txt": 256 * 1024,
  "prompt.txt": MAX_PROMPT,
  "saved-profile.json": 256 * 1024,
});
export const hash = (b) => createHash("sha256").update(b).digest("hex");
export const validId = (id) =>
  typeof id === "string" &&
  /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/.test(
    id,
  );
export async function safeDirectory(path) {
  const p = resolve(path);
  if ((await realpath(p)) !== p || !(await lstat(p)).isDirectory())
    throw Error("Symlink or unsafe handoff directory");
  return p;
}
export async function bounded(path, max) {
  const f = await open(path, constants.O_RDONLY | constants.O_NOFOLLOW);
  try {
    const s = await f.stat();
    if (!s.isFile() || s.size > max)
      throw Error("Unsafe or oversized handoff file");
    const b = Buffer.alloc(s.size + 1);
    let offset = 0;
    while (offset < b.length) {
      const { bytesRead } = await f.read(b, offset, b.length - offset, null);
      if (!bytesRead) break;
      offset += bytesRead;
    }
    if (offset !== s.size) throw Error("Handoff file changed during read");
    return b.subarray(0, offset);
  } finally {
    await f.close();
  }
}
export async function verifySnapshot(dir, expectedHash) {
  await safeDirectory(dir);
  const raw = await bounded(join(dir, "snapshot.json"), 128 * 1024);
  if (!/^[a-f0-9]{64}$/.test(expectedHash) || hash(raw) !== expectedHash)
    throw Error("Snapshot identity mismatch");
  const s = JSON.parse(raw);
  if (
    s.kind !== "reword-outbound-handoff" ||
    s.schemaVersion !== 1 ||
    !validId(s.id) ||
    s.target !== "codex-cli" ||
    !["image", "text"].includes(s.sourceKind) ||
    s.operation !== "terminal-launch-review" ||
    s.acceptedByUser !== false
  )
    throw Error("Unsupported handoff record");
  const names = Object.keys(s.artifacts ?? {}).sort();
  const expected = [
    "package.zip",
    "prompt.txt",
    "saved-profile.json",
    s.sourceKind === "image" ? "reference.png" : "reviewed-source.txt",
  ].sort();
  if (JSON.stringify(names) !== JSON.stringify(expected))
    throw Error("Handoff inventory mismatch");
  const files = {};
  for (const name of names) {
    const b = await bounded(join(dir, name), FILE_LIMITS[name]);
    if (
      hash(b) !== s.artifacts[name].sha256 ||
      b.length !== s.artifacts[name].byteLength
    )
      throw Error("Handoff artifact changed: " + name);
    files[name] = b;
  }
  if (
    s.packageSha256 !== hash(files["package.zip"]) ||
    s.promptSha256 !== hash(files["prompt.txt"]) ||
    s.referenceSha256 !==
      hash(
        files[
          s.sourceKind === "image" ? "reference.png" : "reviewed-source.txt"
        ],
      )
  )
    throw Error("Handoff source binding mismatch");
  return { snapshot: s, files };
}
export function promptText(bytes) {
  return new TextDecoder("utf-8", { fatal: true, ignoreBOM: true }).decode(
    bytes,
  );
}
export function cliArgs(snapshot, dir, prompt) {
  if (Buffer.byteLength(prompt) > MAX_PROMPT || unsafePromptControls(prompt))
    throw Error(
      "Prompt exceeds the CLI limit or contains control/CR characters the target may normalize",
    );
  return [
    "--cd",
    join(dir, "workspace"),
    "--sandbox",
    "read-only",
    "--ask-for-approval",
    "on-request",
    "-c",
    'model_reasoning_effort="medium"',
    "-c",
    'model_provider="openai"',
    "-c",
    "project_doc_max_bytes=0",
    "-c",
    "project_doc_fallback_filenames=[]",
    "-c",
    'web_search="disabled"',
    ...[
      "hooks",
      "apps",
      "plugins",
      "remote_plugin",
      "memories",
      "multi_agent",
      "multi_agent_v2",
      "shell_tool",
      "shell_snapshot",
      "code_mode",
      "code_mode_host",
      "browser_use",
      "computer_use",
      "goals",
      "sleep_tool",
    ].flatMap((n) => ["--disable", n]),
    ...(snapshot.sourceKind === "image"
      ? ["--image", join(dir, "reference.png")]
      : []),
    "--",
    prompt,
  ];
}
